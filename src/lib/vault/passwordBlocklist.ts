// "wallet", "seed" far more often than the general population does).
//
// Deliberately curated rather than exhaustive. zxcvbn's own dictionaries
// run to ~30k entries and several hundred KB, which is not a reasonable
// thing to add to the critical path of a wallet that already ships a 7.7MB
