// Rank is 1-based: the most common entry costs log2(1) = 0 bits, i.e. an
// attacker's very first guess.
export const BLOCKLIST: ReadonlyMap<string, number> = new Map(
  RAW.split("\n")
    .map((w) => w.trim())
    .filter((w) => w.length > 0)
    .map((w, i) => [w, i + 1] as const),
);

// The longest entry, so the matcher never bothers testing substrings that
// cannot possibly be in the list.
export const MAX_BLOCKLIST_LENGTH = Math.max(...[...BLOCKLIST.keys()].map((w) => w.length));
