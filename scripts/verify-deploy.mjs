#!/usr/bin/env node
// Checks that what spendrr.app actually serves is byte-for-byte the build of a
// commit that exists in git. The threat: someone with access to the Cloudflare
// account (or a leaked deploy token) swaps in modified JS, which would read
// every user's seed on their next unlock. Nothing inside the app can detect
// that, since the attacker writes the app. Run hourly by
// .github/workflows/deploy-watch.yml, which builds the deployed commit itself.
//
//   node scripts/verify-deploy.mjs commit [origin]          prints the deployed commit
//   node scripts/verify-deploy.mjs manifest <dist> <commit>  prints {commit, files: {path: sha256}}
//   node scripts/verify-deploy.mjs verify <manifest.json> [origin]
//
// Limits: only static assets are checked, not the Worker's own code or the
// HTML it rewrites for /@name pages; and a server that answers the checker
// differently from real users (by IP, UA) would pass.

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

const DEFAULT_ORIGIN = "https://spendrr.app";

// In dist/ but not served as-is: manifest.json is generated by the Worker
// (light/dark variant, run_worker_first), _headers is Cloudflare config.
const NOT_SERVED_AS_IS = new Set(["manifest.json", "_headers", "_redirects"]);

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

async function fetchBytes(origin, path) {
  // The query string only defeats intermediate caches; the asset layer ignores it.
  const res = await fetch(`${origin}/${path}?verify=${Date.now()}`, {
    cache: "no-store",
    redirect: "follow",
  });
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

function listFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...listFiles(full));
    else out.push(full);
  }
  return out;
}

async function deployedCommit(origin) {
  const info = JSON.parse((await fetchBytes(origin, "build-info.json")).toString("utf8"));
  if (info.dirty) {
    throw new Error(
      `Deployed build of ${info.commit} was made from a tree with uncommitted changes, so no commit reproduces it.`,
    );
  }
  if (typeof info.commit !== "string" || !/^[0-9a-f]{40}$/.test(info.commit)) {
    throw new Error(`build-info.json has no usable commit: ${JSON.stringify(info)}`);
  }
  return info.commit;
}

function manifest(dist, commit) {
  const files = {};
  for (const file of listFiles(dist)) {
    const path = relative(dist, file).split(sep).join("/");
    if (NOT_SERVED_AS_IS.has(path)) continue;
    files[path] = sha256(readFileSync(file));
  }
  return { commit, files };
}

async function verify(expected, origin) {
  const problems = [];
  const paths = Object.keys(expected.files).sort();
  // A handful at a time: the WASM is ~7.7 MB and there is no hurry.
  for (let i = 0; i < paths.length; i += 8) {
    await Promise.all(
      paths.slice(i, i + 8).map(async (path) => {
        // index.html is what "/" serves; asking for /index.html gets a redirect there anyway.
        const served = path === "index.html" ? "" : path;
        try {
          const actual = sha256(await fetchBytes(origin, served));
          if (actual !== expected.files[path]) problems.push(`${path}: served ${actual}, built ${expected.files[path]}`);
        } catch (e) {
          problems.push(`${path}: ${e.message}`);
        }
      }),
    );
  }
  return { checked: paths.length, problems };
}

const [cmd, a, b] = process.argv.slice(2);
try {
  if (cmd === "commit") {
    console.log(await deployedCommit(a ?? DEFAULT_ORIGIN));
  } else if (cmd === "manifest" && a && b) {
    console.log(JSON.stringify(manifest(a, b), null, 2));
  } else if (cmd === "verify" && a) {
    const origin = b ?? DEFAULT_ORIGIN;
    const expected = JSON.parse(readFileSync(a, "utf8"));
    // The deploy may have moved on since the manifest was built; that is not tampering.
    const now = await deployedCommit(origin);
    if (now !== expected.commit) throw new Error(`Deployed commit changed to ${now} during the check, run again.`);
    const { checked, problems } = await verify(expected, origin);
    if (problems.length > 0) {
      console.error(`MISMATCH: ${origin} does not serve the build of ${expected.commit}`);
      for (const p of problems) console.error(`  ${p}`);
      process.exit(1);
    }
    console.log(`OK: all ${checked} files on ${origin} match the build of ${expected.commit}`);
  } else {
    console.error("usage: verify-deploy.mjs commit [origin] | manifest <dist> <commit> | verify <manifest.json> [origin]");
    process.exit(2);
  }
} catch (e) {
  console.error(`ERROR: ${e.message}`);
  process.exit(1);
}
